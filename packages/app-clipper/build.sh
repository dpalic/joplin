#!/usr/bin/env bash
# Builds the Joplin Web Clipper so it can be loaded as an unpacked extension
# (chrome://extensions -> Developer mode -> Load unpacked -> this folder).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(git -C "$SCRIPT_DIR" rev-parse --show-toplevel)"
LIB_DIR="$SCRIPT_DIR/../lib"
POPUP_DIR="$SCRIPT_DIR/popup"
ENV_FILE="$SCRIPT_DIR/util/joplinEnv.mjs"
TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

# Asks a yes/no question, default yes. Without a terminal the default is used.
confirm() {
	[ -t 0 ] || return 0
	local answer
	read -r -p "$1 [Y/n] " answer
	[[ ! "$answer" =~ ^[Nn] ]]
}

# Files changed in the working tree (tracked or new), relative to the repo root.
changed_files() {
	{ git -C "$REPO_ROOT" diff --name-only HEAD; git -C "$REPO_ROOT" ls-files --others --exclude-standard; } | sort -u
}

# "prod" talks to a normally installed Joplin (port 41184); "dev" talks to Joplin
# running from source (port 27583). Set JOPLIN_CLIPPER_ENV to skip the question.
CLIPPER_ENV="${JOPLIN_CLIPPER_ENV:-}"
if [ -z "$CLIPPER_ENV" ] && [ -t 0 ]; then
	echo "Which Joplin should this build talk to?"
	echo "  1) prod - the installed Joplin app (port 41184)"
	echo "  2) dev  - Joplin running from source (port 27583)"
	read -r -p "Choose [1]: " choice
	case "${choice:-1}" in
		2) CLIPPER_ENV=dev ;;
		*) CLIPPER_ENV=prod ;;
	esac
fi
CLIPPER_ENV="${CLIPPER_ENV:-prod}"
case "$CLIPPER_ENV" in
	dev|prod) ;;
	*) echo "JOPLIN_CLIPPER_ENV must be 'dev' or 'prod', got '$CLIPPER_ENV'" >&2; exit 1 ;;
esac

echo "==> Linting changed JavaScript files"
mapfile -t JS_FILES < <(changed_files | grep -E '^packages/app-clipper/.*\.(js|mjs)$' | grep -vE '/(node_modules|build)/|/content_scripts/(Readability|JSDOMParser|clipperUtils)' || true)
if [ "${#JS_FILES[@]}" -eq 0 ]; then
	echo "No changed JavaScript files."
elif [ -x "$REPO_ROOT/node_modules/.bin/eslint" ]; then
	(cd "$REPO_ROOT" && node_modules/.bin/eslint --quiet "${JS_FILES[@]}")
else
	echo "SKIPPED: the monorepo dependencies are not installed. Run 'yarn install' in $REPO_ROOT to enable linting." >&2
fi

# Same file types the repository's own 'yarn spellcheck' covers.
echo "==> Spellchecking changed ts/tsx/md/mdx files"
mapfile -t SPELL_FILES < <(changed_files | grep -E '\.(ts|tsx|md|mdx)$' || true)
if [ "${#SPELL_FILES[@]}" -eq 0 ]; then
	echo "No changed spellcheckable files."
else
	(cd "$REPO_ROOT" && npx --yes cspell@5.21.2 --no-progress --no-summary --config cspell.json "${SPELL_FILES[@]}")
fi

echo "==> Setting clipper environment to: $CLIPPER_ENV"
printf '// AUTOGENERATED by release-clipper\n\nexport default () => '"'"'%s'"'"';\n' "$CLIPPER_ENV" > "$ENV_FILE"

echo "==> Installing popup dependencies"
cd "$POPUP_DIR"
npm install --ignore-scripts

echo "==> Running popup postinstall"
node postinstall.js

# content_scripts/clipperUtils.js is gitignored and normally copied from the
# compiled packages/lib. Compile that single self-contained file instead of
# the whole monorepo.
echo "==> Compiling clipperUtils.ts"
npx --yes -p typescript@5 tsc "$LIB_DIR/clipperUtils.ts" \
	--outDir "$TMP_DIR" --module commonjs --target es2019 \
	--lib es2019,dom,dom.iterable --skipLibCheck
cp "$TMP_DIR/clipperUtils.js" "$SCRIPT_DIR/content_scripts/clipperUtils.js"

echo "==> Building popup"
npm run build

for f in popup/build/index.html content_scripts/clipperUtils.js options/options.html; do
	[ -f "$SCRIPT_DIR/$f" ] || { echo "Missing expected output: $f" >&2; exit 1; }
done

# util/joplinEnv.mjs is tracked and must match the committed version before
# pushing. The popup bundle already contains the chosen environment; only the
# service worker reads the file at run time, and it uses it for the toolbar icon.
if ! git -C "$REPO_ROOT" diff --quiet HEAD -- "$ENV_FILE"; then
	if confirm "util/joplinEnv.mjs differs from the committed version. Restore it now (required before pushing)?"; then
		git -C "$REPO_ROOT" restore --source=HEAD --staged --worktree -- "$ENV_FILE"
		echo "Restored util/joplinEnv.mjs."
	else
		echo "Left util/joplinEnv.mjs modified. Restore it before pushing: git restore util/joplinEnv.mjs"
	fi
fi

echo "==> Done. Load $SCRIPT_DIR as an unpacked extension."
